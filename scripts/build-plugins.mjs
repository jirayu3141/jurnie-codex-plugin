import { readFile, readdir, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
const source = path.join(root, "plugin-source");
const meta = JSON.parse(await readFile(path.join(source, "metadata.json"), "utf8"));
if (!/^\d+\.\d+\.\d+$/.test(meta.version)) throw new Error("Use a release SemVer version");
if (!/^\d+\.\d+\.\d+$/.test(meta.cursorBridgeVersion)) throw new Error("Pin the Cursor bridge version");
if (new URL(meta.mcpUrl).protocol !== "https:") throw new Error("Use the HTTPS MCP endpoint");

const { name, version, description, author, homepage, repository, license, keywords } = meta;
const manifest = { name, version, description, author, homepage, repository, license, keywords };
const interfaceMetadata = {
  displayName: meta.displayName,
  shortDescription: "Turn goals into next actions",
  longDescription: "Connect your Jurnie account to review personal and shared Journeys, plan the day, manage and assign tasks, track habits, set intentions, work with calendar events, and schedule follow-through. Access follows the permissions you choose during Jurnie sign-in.",
  developerName: author.name,
  category: "Productivity",
  capabilities: ["Interactive", "Write"],
  websiteURL: author.url,
  supportURL: meta.supportUrl,
  privacyPolicyURL: meta.privacyPolicyUrl,
  termsOfServiceURL: meta.termsOfServiceUrl,
  defaultPrompt: [
    "Review my Jurnie priorities and plan today.",
    "Show my overdue tasks and suggest the next three actions.",
    "Assign a Journey task to the right team member.",
  ],
  brandColor: "#030213",
  composerIcon: "./assets/logo.png",
  logo: "./assets/logo.png",
  screenshots: [],
};
const remote = { mcpServers: { [name]: { type: "http", url: meta.mcpUrl } } };
const portableMcp = {
  $schema: "https://agent-plugins.org/schemas/1.0.0/mcp.schema.json",
  mcpServers: { [name]: { type: "streamable-http", url: meta.mcpUrl } },
};
const outputs = new Map();
const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const put = (relative, value) => outputs.set(relative, Buffer.from(typeof value === "string" ? value : json(value)));

async function copyTree(from, to) {
  for (const entry of await readdir(from, { withFileTypes: true })) {
    const input = path.join(from, entry.name);
    const output = `${to}/${entry.name}`;
    if (entry.isDirectory()) await copyTree(input, output);
    else if (entry.isFile()) outputs.set(output, await readFile(input));
    else throw new Error(`Unsupported source entry: ${input}`);
  }
}

for (const [host, dir] of [["Codex", "jurnie"], ["Claude", "jurnie-claude"], ["Cursor", "jurnie-cursor"]]) {
  const prefix = `plugins/${dir}`;
  await copyTree(path.join(source, "skills"), `${prefix}/skills`);
  await copyTree(path.join(source, "assets"), `${prefix}/assets`);
  outputs.set(`${prefix}/LICENSE`, await readFile(path.join(root, "LICENSE")));
  put(`${prefix}/README.md`, `<!-- Generated by scripts/build-plugins.mjs. Edit plugin-source/ instead. -->
# ${host === "Claude" ? meta.claude.displayName : `Jurnie for ${host}`}

Connect ${host} to your Jurnie account to review goals, plan your day, manage personal or shared tasks, track habits, set daily intentions, and schedule follow-through. The package includes the shared Jurnie workflow skill and a connection to Jurnie's OAuth-protected MCP server.

An existing Jurnie account is required. Free accounts can connect; existing product limits apply. The plugin offers no purchases. Sign in through Jurnie and choose only the access you need. Deletions need separate permission and confirmation. Calendar event creation requires a connected Google Calendar.

${host === "Cursor" ? `Cursor uses Node.js/npm and the pinned mcp-remote@${meta.cursorBridgeVersion} bridge because Jurnie's authorization provider does not accept Cursor's native callback URI. The bridge runs locally and opens Jurnie's OAuth flow in your browser.\n\n` : ""}## Get started

[Public setup instructions](${homepage}#${host.toLowerCase()})

${host === "Claude" ? `Claude Code: \`/plugin install ${meta.claude.name} --marketplace jirayu3141/jurnie-codex-plugin\`\n\nThis is the goals and tasks service at jurnie.co. The directory name distinguishes it from the separate meeting-notes connector at jurnie.io.\n\n` : ""}Try: “Show my Jurnie tasks”, “Plan today from my Jurnie priorities”, or “Create a personal Jurnie task with no Journey called Review the launch checklist.” Confirm a write when your client asks. The assistant should report changes only after a successful tool response.

Jurnie cannot send email, process payments, or read Google Drive files. Your connection exposes only data accessible to your signed-in account, according to the scopes you grant. You can revoke access in Jurnie's settings.

## Support and policies

- [Help](https://www.jurnie.co/help) or ${author.email}
- [Privacy](https://www.jurnie.co/privacy)
- [Terms](https://www.jurnie.co/terms)
- License: ${license}
`);
  if (host === "Codex") {
    put(`${prefix}/plugin.json`, {
      $schema: "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json",
      ...manifest,
      extensions: { "com.openai": { interface: interfaceMetadata } },
    });
    put(`${prefix}/mcp.json`, portableMcp);
    put(`${prefix}/.codex-plugin/plugin.json`, {
      ...manifest, skills: "./skills/", mcpServers: "./.mcp.json", interface: interfaceMetadata,
    });
    put(`${prefix}/.mcp.json`, remote);
  } else if (host === "Claude") {
    put(`${prefix}/.claude-plugin/plugin.json`, {
      ...manifest,
      ...meta.claude,
      privacyPolicyUrl: meta.privacyPolicyUrl,
      supportUrl: meta.supportUrl,
      termsOfServiceUrl: meta.termsOfServiceUrl,
      documentationUrl: `${homepage}#claude`,
    });
    put(`${prefix}/.mcp.json`, remote);
  } else {
    put(`${prefix}/.cursor-plugin/plugin.json`, { ...manifest, displayName: meta.displayName, logo: "assets/logo.png" });
    put(`${prefix}/mcp.json`, {
      mcpServers: { [name]: { command: "npx", args: ["-y", `mcp-remote@${meta.cursorBridgeVersion}`, meta.mcpUrl] } },
    });
  }
}

for (const [host, dir] of [["claude", "jurnie-claude"], ["cursor", "jurnie-cursor"]]) {
  put(`.${host}-plugin/marketplace.json`, {
    name: "jurnie-plugins",
    owner: { name: author.name, email: author.email },
    metadata: { description: "Jurnie planning and follow-through", version },
    plugins: [{ name: host === "claude" ? meta.claude.name : name, source: `./plugins/${dir}`, description }],
  });
}

const stale = [];
for (const [relative, contents] of outputs) {
  const destination = path.join(root, relative);
  if (check) {
    const current = await readFile(destination).catch(() => null);
    if (!current?.equals(contents)) stale.push(relative);
  } else {
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, contents);
  }
}
if (stale.length) throw new Error(`Generated packages are stale. Run npm run build:\n${stale.join("\n")}`);
console.log(`${check ? "Verified" : "Generated"} ${outputs.size} files for Jurnie ${version} from one shared source.`);
